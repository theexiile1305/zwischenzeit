#!/usr/bin/env python3
"""Generate DesignTokens.swift from design/tokens.json.

The iOS stand-in for tokens.css + the Tailwind mapping: components use
DS.Color.textMuted, DS.Space.s4, DS.Layout.timeColumnWidth, never raw values.

    python3 scripts/gen_swift_tokens.py design/tokens.json \
        Packages/ZwischenzeitKit/Sources/DesignSystem/DesignTokens.swift
"""

import json
import re
import sys


def camel(name):
    parts = re.split(r"[-_ ]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def rgb(hex_):
    h = hex_.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def main(src, dst):
    with open(src, encoding="utf-8") as fh:
        t = json.load(fh)
    light, dark = t["color"], t.get("color-dark", t["color"])
    out = [
        "// Generated by scripts/gen_swift_tokens.py from tokens.json. Do not edit.",
        "",
        "import SwiftUI",
        "#if canImport(UIKit)",
        "import UIKit",
        "#else",
        "import AppKit",
        "#endif",
        "",
        "public enum DS {}",
        "",
        "extension DS {",
        "    public enum Color {",
    ]
    for name in light:
        l, d = rgb(light[name]), rgb(dark[name])
        out.append(
            "        public static let %s = dynamic(light: (%.4f, %.4f, %.4f), dark: (%.4f, %.4f, %.4f))"
            % ((camel(name),) + l + d))
    out += [
        "",
        "        static func dynamic(light: (Double, Double, Double), dark: (Double, Double, Double)) -> SwiftUI.Color {",
        "            #if os(watchOS)",
        "            // watchOS is always dark and has no dynamic UIColor provider.",
        "            SwiftUI.Color(red: dark.0, green: dark.1, blue: dark.2)",
        "            #elseif canImport(UIKit)",
        "            SwiftUI.Color(uiColor: UIColor { traits in",
        "                let c = traits.userInterfaceStyle == .dark ? dark : light",
        "                return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)",
        "            })",
        "            #else",
        "            SwiftUI.Color(nsColor: NSColor(name: nil) { appearance in",
        "                let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua",
        "                let c = isDark ? dark : light",
        "                return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: 1)",
        "            })",
        "            #endif",
        "        }",
        "    }",
        "",
        "    public enum Space {",
    ]
    for v in t["space"]:
        out.append("        public static let s%d: CGFloat = %d" % (v, v))
    out += ["    }", "", "    public enum Radius {"]
    for k, v in t["radius"].items():
        out.append("        public static let %s: CGFloat = %d" % (camel(k), v))
    out += ["    }", "", "    public enum Layout {"]
    for k, v in t["layout"].items():
        out.append("        public static let %s: CGFloat = %s" % (camel(k), v))
    out += ["    }", "", "    public enum Shadow {"]
    for k, v in t["shadow"].items():
        out.append(
            "        public static let %s = (opacity: %s, radius: CGFloat(%s), y: CGFloat(%s))"
            % (camel(k), v["opacity"], v["radius"], v["y"]))
    out += ["    }", "}", ""]
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote %s (%d colours)" % (dst, len(light)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
